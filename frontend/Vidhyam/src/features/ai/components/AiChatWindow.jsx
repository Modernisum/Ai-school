// ─── Parse markdown table into headers + rows ─────────────────────────────────
function parseMarkdownTable(text) {
  const lines = text.split("\n").filter(l => l.trim().startsWith("|") && l.trim().endsWith("|"));
  if (lines.length < 2) return null;

  const extractCells = (line) => {
    let content = line.trim();
    if (content.startsWith("|")) content = content.slice(1);
    if (content.endsWith("|")) content = content.slice(0, -1);
    return content.split("|").map(c => {
      let val = c.trim();
      return val === "" ? "-" : val;
    });
  };

  const headers = extractCells(lines[0]);
  const isSep = lines[1].replace(/[\|\-\:\s]/g, "").length === 0;
  if (!isSep || headers.length === 0) return null;

  const rows = lines.slice(2).map(extractCells);
  return { headers, rows };
}

