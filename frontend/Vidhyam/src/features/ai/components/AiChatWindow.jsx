// ─── Parse [SUGGESTIONS:{...}] block from message text ───────────────────────
function parseSuggestions(text) {
  if (!text) return { cleanText: text || "", suggestions: [] };
  const match = text.match(/\[SUGGESTIONS:(\{.*?\})\]$/s);
  if (!match) return { cleanText: text, suggestions: [] };
  try {
    const data = JSON.parse(match[1]);
    return {
      cleanText: text.slice(0, text.length - match[0].length).trim(),
      suggestions: Array.isArray(data.questions) ? data.questions : [],
    };
  } catch {
    return { cleanText: text, suggestions: [] };
  }
}

// ─── Inline bold parser ───────────────────────────────────────────────────────
function parseInlineBold(text) {
  const parts = text.split(/(\*\*.*?\*\*)/g);
  return parts.map((p, i) => {
    if (p.startsWith("**") && p.endsWith("**")) {
      return <strong key={i} className="font-semibold text-white">{p.slice(2, -2)}</strong>;
    }
    return p;
  });
}

// ─── Main markdown renderer ───────────────────────────────────────────────────
function renderMarkdown(text) {
  if (!text) return null;

  // Split by code blocks first
  const codeBlockParts = text.split(/(```[\s\S]*?```)/g);

  return codeBlockParts.map((part, partIdx) => {
    // Handle fenced code blocks
    if (part.startsWith("```") && part.endsWith("```")) {
      const inner = part.slice(3, -3).trim();
      const firstNewline = inner.indexOf("\n");
      const lang = firstNewline > -1 ? inner.slice(0, firstNewline).trim().toLowerCase() : "";
      const code = firstNewline > -1 ? inner.slice(firstNewline + 1) : inner;

      if (lang === "chart") {
        return (
          <ChartErrorBoundary key={partIdx}>
            <ChartRenderer jsonString={code} />
          </ChartErrorBoundary>
        );
      }

      return (
        <div key={partIdx} className="my-2 bg-black/60 rounded-lg overflow-hidden border border-white/5 font-mono">
          {lang && (
            <div className="bg-white/5 px-3 py-1 text-[10px] text-slate-400 uppercase tracking-wider border-b border-white/5">
              {lang}
            </div>
          )}
          <pre className="p-3 overflow-x-auto text-[11px] text-slate-100 leading-relaxed">
            <code>{code}</code>
          </pre>
        </div>
      );
    }

    // For normal text: scan line by line, detect table blocks
    const lines = part.split("\n");
    const elements = [];
    let i = 0;

    while (i < lines.length) {
      const line = lines[i];

      // Detect start of markdown table
      if (line.trim().startsWith("|") && line.trim().endsWith("|")) {
        // Gather all consecutive pipe lines
        const tableLines = [];
        while (i < lines.length && lines[i].trim().startsWith("|") && lines[i].trim().endsWith("|")) {
          tableLines.push(lines[i]);
          i++;
        }
        const parsed = parseMarkdownTable(tableLines.join("\n"));
        if (parsed && parsed.rows.length > 0) {
          elements.push(
            <DataTable key={`tbl-${partIdx}-${elements.length}`} headers={parsed.headers} rows={parsed.rows} />
          );
        }
        continue;
      }

      // Bullet list
      if (line.trim().startsWith("- ") || line.trim().startsWith("* ")) {
        elements.push(
          <ul key={`ul-${partIdx}-${i}`} className="list-disc pl-5 my-1 text-xs text-slate-200">
            <li>{parseInlineBold(line.trim().slice(2))}</li>
          </ul>
        );
        i++;
        continue;
      }

      // Heading
      if (line.trim().startsWith("# ")) {
        elements.push(
          <h3 key={`h-${partIdx}-${i}`} className="text-sm font-bold text-white mt-3 mb-1">
            {line.trim().slice(2)}
          </h3>
        );
        i++;
        continue;
      }

      // Empty line → spacer
      if (line.trim() === "") {
        if (elements.length > 0) {
          elements.push(<div key={`sp-${partIdx}-${i}`} className="h-1" />);
        }
        i++;
        continue;
      }

      // Normal paragraph
      elements.push(
        <p key={`p-${partIdx}-${i}`} className="my-1 text-xs text-slate-200 leading-relaxed">
          {parseInlineBold(line)}
        </p>
      );
      i++;
    }

    return <React.Fragment key={partIdx}>{elements}</React.Fragment>;
  });
}

